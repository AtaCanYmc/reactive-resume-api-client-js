let currentLang = "en";

export function getLanguage() {
  return currentLang;
}

export function t(key) {
  const langObj = translations[currentLang] || translations.en;
  return langObj[key] || translations.en[key] || key;
}

export function applyLanguage(lang) {
  currentLang = SUPPORTED_LANGUAGES.includes(lang) ? lang : "en";
  localStorage.setItem(LANG_STORAGE_KEY, currentLang);
  document.documentElement.lang = currentLang;

  const docTitleVal = t("docTitle");
  if (docTitleVal) {
    document.title = docTitleVal;
  }

  // Text contents
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (val !== undefined) {
      el.textContent = val;
    }
  });

  // Placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    const val = t(key);
    if (val !== undefined) {
      el.placeholder = val;
    }
  });

  // Titles
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    const val = t(key);
    if (val !== undefined) {
      el.title = val;
    }
  });

  // Aria-labels
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria-label");
    const val = t(key);
    if (val !== undefined) {
      el.setAttribute("aria-label", val);
    }
  });

  // Ensure radio button is synced
  const radio = document.querySelector(`input[name="langSelect"][value="${currentLang}"]`);
  if (radio) {
    radio.checked = true;
  }
}

export function initLanguage() {
  const saved = localStorage.getItem(LANG_STORAGE_KEY);
  if (saved && SUPPORTED_LANGUAGES.includes(saved)) {
    applyLanguage(saved);
  } else {
    // Detect browser language
    const navLang = (navigator.language || "").slice(0, 2).toLowerCase();
    if (SUPPORTED_LANGUAGES.includes(navLang)) {
      applyLanguage(navLang);
    } else {
      applyLanguage("en");
    }
  }

  const radio = document.querySelector(`input[name="langSelect"][value="${currentLang}"]`);
  if (radio) {
    radio.checked = true;
  }
}
